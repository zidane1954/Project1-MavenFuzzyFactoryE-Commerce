WITH PengeluaranPerUser AS (
    SELECT 
        user_id, 
        SUM(price_usd) AS total_belanja_user,
        COUNT(order_id) AS frekuensi_beli
    FROM orders
    GROUP BY user_id
)
SELECT 
   ROUND(AVG(total_belanja_user),2) AS rata_rata_pengeluaran_per_pembeli
FROM PengeluaranPerUser;

